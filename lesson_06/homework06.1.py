"""Homework 6.1. Рахування унікальних символів в строці."""


# Порахувати кількість унікальних символів в строці.
# Якщо їх більше 10 - вивести в консоль True, інакше - False.
# Строку отримати за допомогою функції input()


# Отримати строку від користувача
input_string = input('Введіть строку: ')

# Визначити кількість унікальних символів
unique_symbols = len(set(input_string))

# Вивести True, якщо унікальних символів більше 10, інакше - False
print(True if unique_symbols > 10 else False)
